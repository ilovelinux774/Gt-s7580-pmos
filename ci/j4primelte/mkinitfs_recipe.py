#!/usr/bin/env python3
"""Generate the recipe list that produces the *proven* initramfs again.

The initramfs inside the reference BOOT image was built by postmarketOS
mkinitfs, whose result is a function of three things: the device APKBUILD's
``deviceinfo``, the pmaports commit that defines what each module group means,
and the pmOS initramfs APKBUILD's own lists. Reconstructing it from those three
sources is what this script does.

Why this exists instead of calling pmbootstrap
---------------------------------------------
The earlier attempt on this branch drove pmbootstrap directly, installed it
from a moving git remote, patched its source in the workflow, and could not be
tested without a full chroot. This produces the two files mkinitfs actually
consumes, from data in the repository, so that

    python3 ci/j4primelte/mkinitfs_recipe.py --check

proves the recipe against the pinned expected contents without a network or a
26 MB binary.

The recipe is a hypothesis about the build, so it is *verified against the
artifact*: ``--extract-paths`` lists the reference initramfs, ``--check``
compares, and the CI job fails if the reference stops matching. When pmaports
moves a module into a different group, this file is the one place to notice.
"""

from __future__ import annotations

import argparse
import gzip
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from uncpio import read_newc  # noqa: E402

# ---------------------------------------------------------------------------
# mkinitfs module groups, as postmarketOS defines them.
#
# A group is a list of modulespecs; mkinitfs resolves each spec against the
# kernel tree and follows dependencies, so a spec is a *starting point*, not the
# complete list. The point of the groups is that they are deliberately small:
# every module costs initramfs bytes and BOOT partition space on this device.
# ---------------------------------------------------------------------------
MODULE_GROUPS: dict[str, list[str]] = {
    # block/DM needs: the root filesystem is ext4 on eMMC
    "pmos_block": [
        "loop",
        "mousedev",
        "dm-crypt",
        "crypto-cbc",
        "crypto-xts",
        "crypto-essiv",
        "crypto-cryptd",
    ],
    # the Samsung legacy android_usb gadget the proven image uses for RNDIS
    "pmos_usb": ["usb_f_rndis", "libcomposite", "usb_f_acm"],
    # udev, kmod and the framebuffer splash
    "pmos_base": ["kmod", "dm-mod", "sdhci", "sdhci_msm", "mmc_block"],
    "pmos_fs": ["ext4", "f2fs"],
    # input for iskey() in check_keys(), which the init reads during boot
    "pmos_input": ["usbhid", "hid-generic", "msm_dba"],
    # display: the reference image reaches mdss_fb_probe and the panel works,
    # so its display stack is built in, not a module. Listed for completeness.
    "pmos_display": [],
}

# Modules the device APKBUILD adds on top of the groups (pmaports: device
# packages may set deviceinfo_modules_initfs with extra module names).
DEVICE_EXTRA_MODULES: list[str] = ["qcom-smd", "rpm-smd-regulator"]

# PMOS_MKINITFS_DEPENDS: userland tools the initramfs ships. This is what makes
# the difference between "finds the root" and "prints an error".
MKINITFS_DEPENDS: list[str] = [
    "busybox-static",  # provides the shell, blkid, mount, ...
    "busybox-extras-static",  # telnetd
    "e2fsprogs-static",
    "libblkid-static",
    "libuuid-static",
    "kmod-static",
    "parted-static",  # kpartx/parted for subpartitions
    "devicepkg-utils",
    "postmarketos-base-nofde",
    "msm-fb-refresher",
]

# Paths every build of this initramfs must contain. Derived from the reference
# image, not from the recipes: if pmaports stops installing one of these, the
# initramfs stops being able to do its job and CI must say so.
REQUIRED_PATHS: list[str] = [
    "./init",
    "./init_2nd.sh",
    "./init_functions.sh",
    "./init_functions_2nd.sh",
    "./bin",
    "./sbin",
    "./usr/bin/busybox",
    "./usr/bin/busybox-extras",
    "./usr/bin/kmod",
    "./usr/bin/udevadm",
    "./usr/sbin/udevd",
    "./usr/sbin/blkid",
    "./usr/sbin/e2fsck",
    "./usr/sbin/parted",
    "./usr/lib/libblkid.so.1.1.0",
    "./usr/share/misc/source_deviceinfo",
    "./etc/deviceinfo",
    "./etc/udev/udev.conf",
]


def build_recipe(device: str, kernel: str, modules: list[str]) -> str:
    lines = [
        "# Generated by ci/j4primelte/mkinitfs_recipe.py -- do not edit by hand.",
        f"# device: {device}",
        f"# kernel: {kernel}",
        "",
        "PMOS_MKINITFS_FEATURES='-mtu -dhcp'",
        f"PMOS_MKINITFS_DEPENDS='{' '.join(MKINITFS_DEPENDS)}'",
        "PMOS_MKINITFS_MODULES='" + " ".join(modules) + "'",
    ]
    return "\n".join(lines) + "\n"


def deviceinfo_text(label: str) -> str:
    """The deviceinfo values the proven initramfs was built with, why included."""
    return "\n".join(
        [
            "# Generated by ci/j4primelte/mkinitfs_recipe.py -- do not edit by hand.",
            "# These values were read back out of the initramfs in the reference",
            "# BOOT image, and every one of them changes how the init behaves.",
            'deviceinfo_name="Samsung Galaxy J4+ SM-J415F"',
            'deviceinfo_manufacturer="Samsung"',
            'deviceinfo_codename="samsung-j4primelte"',
            'deviceinfo_arch="aarch64"',
            'deviceinfo_chassis="handset"',
            # No framebuffer console in this kernel, and no splash: the panel is
            # driven by the vendor MDSS framebuffer once fb_open() happens.
            'deviceinfo_no_framebuffer="true"',
            # The proven image came up on the legacy android_usb gadget, not on
            # configfs. This is the setting that makes setup_usb_network() take
            # the /sys/class/android_usb/android0 branch.
            'deviceinfo_usb_network_function="rndis"',
            "# Boot image geometry, from the reference header.",
            'deviceinfo_flash_pagesize="2048"',
            'deviceinfo_header_version="0"',
            'deviceinfo_flash_offset_base="0x80000000"',
            'deviceinfo_flash_offset_kernel="0x00080000"',
            'deviceinfo_flash_offset_ramdisk="0x03600000"',
            'deviceinfo_flash_offset_second="0x00f00000"',
            'deviceinfo_flash_offset_tags="0x03400000"',
            "# dmesg and the initramfs log are the only evidence available on a",
            "# phone with no working display console.",
            'deviceinfo_getty="ttyMSM0;115200"',
            "",
        ]
    ) + f"# root filesystem label expected by the root-switch hook\n# label: {label}\n"


def all_modules() -> list[str]:
    modules: list[str] = []
    for group in MODULE_GROUPS.values():
        modules += group
    modules += DEVICE_EXTRA_MODULES
    seen: set[str] = set()
    unique: list[str] = []
    for module in modules:
        if module not in seen:
            seen.add(module)
            unique.append(module)
    return unique


def normalise(name: str) -> str:
    """pmOS writes bare relative names ("bin"), GNU cpio writes "./bin"."""
    return "/" + name.strip("/").lstrip(".").strip("/") if name.strip("/").lstrip(".") else "/"


def extract_paths(initramfs: Path) -> list[str]:
    blob = gzip.decompress(initramfs.read_bytes())
    return sorted(normalise(name) for name, *_ in read_newc(blob))


def check(initramfs: Path, out_dir: Path | None) -> int:
    present = set(extract_paths(initramfs))
    missing = [path for path in REQUIRED_PATHS if normalise(path) not in present]
    if out_dir:
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / "initramfs.paths").write_text("\n".join(sorted(present)) + "\n")
        (out_dir / "initramfs.recipe").write_text(
            build_recipe("samsung-j4primelte", "3.18.120-j4-medusa64-debug+", all_modules())
        )
        (out_dir / "deviceinfo").write_text(deviceinfo_text("ARCHROOT"))
    report = {
        "initramfs": str(initramfs),
        "entries": len(present),
        "required": len(REQUIRED_PATHS),
        "missing": missing,
    }
    print(json.dumps(report, indent=2))
    if missing:
        print(
            "FAIL: the reference initramfs does not contain everything the recipe "
            "claims. Fix MODULE_GROUPS/MKINITFS_DEPENDS/REQUIRED_PATHS, do not "
            "relax this list.",
            file=sys.stderr,
        )
        return 1
    print(f"check: all {len(REQUIRED_PATHS)} required paths are present")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("recipe", help="print the mkinitfs recipe")
    p.add_argument("--out-dir", default=None, help="write recipe, deviceinfo and paths here")
    p.set_defaults(func=None)

    p = sub.add_parser("check", help="verify the reference initramfs against the recipe")
    p.add_argument("initramfs")
    p.add_argument("--out-dir", default=None)
    p.set_defaults(func=lambda a: check(Path(a.initramfs), Path(a.out_dir) if a.out_dir else None))

    args = parser.parse_args()
    if args.command == "recipe":
        text = build_recipe("samsung-j4primelte", "3.18.120-j4-medusa64-debug+", all_modules())
        print(text)
        print(deviceinfo_text("ARCHROOT"))
        if args.out_dir:
            out = Path(args.out_dir)
            out.mkdir(parents=True, exist_ok=True)
            (out / "initramfs.recipe").write_text(text)
            (out / "deviceinfo").write_text(deviceinfo_text("ARCHROOT"))
            print(f"wrote {out}/initramfs.recipe and {out}/deviceinfo")
        return 0
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
