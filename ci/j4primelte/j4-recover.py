def payload(blob):
    return base64.b64decode(''.join(blob.split())).decode()


WIFI_TEXT = payload(WIFI_B64)
LXQT_TEXT = payload(LXQT_B64)

INIT_TEXT = r"""#!/sbin/openrc-run
# J4_FIRSTBOOT_V1 - restore the pieces that are installed live on this phone.
#
# The CI rootfs image cannot contain the WCNSS firmware (it lives on the stock
# APNHLOS/VENDOR partitions) or the LXQt desktop (downloaded with apk). Both
# used to be installed by hand after flashing, which means they were lost on
# every rootfs flash. This service restores them at boot instead.
name="j4-firstboot"
description="Restore J4+ Wi-Fi firmware, radio and the LXQt desktop"

depend() {
    need localmount
    after j4-usb-debug
}

start() {
    ebegin "J4+ first-boot recovery"
    /usr/local/sbin/j4-recover --boot
    eend $?
}

stop() {
    # Bring-up only; nothing to shut down.
    return 0
}
"""

CONF_TEXT = r"""# J4_FIRSTBOOT_V1 - tuning for the first-boot recovery service.
#
# Restore the WCNSS firmware into /lib/firmware from the stock partitions
# (APNHLOS mmcblk0p45 and VENDOR mmcblk0p48). Mounts are read-only and no
# existing file is ever overwritten.
J4_FIRSTBOOT_FIRMWARE="yes"
#
# Reinstall the LXQt tablet desktop when it is missing. It needs a working
# network, so the download runs detached after boot instead of blocking it.
J4_FIRSTBOOT_DESKTOP="yes"
"""


class SetupError(Exception):
    pass


def log(message):
    line = '%s %s' % (time.strftime('%Y-%m-%dT%H:%M:%S'), message)
    try:
        LOG.parent.mkdir(parents=True, exist_ok=True)
        with LOG.open('a') as handle:
            handle.write(line + '\n')
    except OSError:
        pass
    print(message, flush=True)


def run(*args, timeout=120):
    try:
        proc = subprocess.run(args, capture_output=True, text=True, timeout=timeout)
    except FileNotFoundError as exc:
        raise SetupError(str(exc))
    except subprocess.TimeoutExpired:
        raise SetupError('%s timed out' % ' '.join(args))
    if proc.returncode != 0:
        raise SetupError('%s failed: %s' % (' '.join(args), proc.stderr.strip()))
    return proc.stdout


def quiet(*args, timeout=120):
    try:
        return run(*args, timeout=timeout)
    except SetupError as exc:
        log('WARN: %s' % exc)
        return ''


def check_device():
    if not DEVICEINFO.is_file():
        raise SetupError('%s missing; this is not the expected j4primelte system'
                         % DEVICEINFO)
    if 'samsung-j4primelte' not in DEVICEINFO.read_text():
        raise SetupError('Not the expected j4primelte device')


def firmware_sources():
    """(source on a stock partition, path relative to /lib/firmware)."""
    pairs = []
    for name in [MDT] + ['wcnss.b%s' % n for n in SEGMENTS]:
        pairs.append((APNHLOS / 'image' / name, name))
    for name in PRIMA:
        pairs.append((VENDOR / 'firmware' / 'wlan' / 'prima' / name,
                      'wlan/prima/' + name))
    return pairs


def firmware_missing():
    return [rel for _, rel in firmware_sources() if not (FIRMWARE / rel).is_file()]


def is_mounted(target):
    try:
        mounts = Path('/proc/mounts').read_text()
    except OSError:
        return False
    return any(parts[1] == str(target)
               for parts in (line.split() for line in mounts.splitlines())
               if len(parts) > 1)


def ensure_mount(target, dev, fstype, options):
    target.mkdir(parents=True, exist_ok=True)
    if is_mounted(target):
        return False
    log('mounting %s read-only at %s' % (dev, target))
    run('mount', '-t', fstype, '-o', options, dev, str(target), timeout=60)
    return True


def stage_firmware():
    missing = firmware_missing()
    if not missing:
        log('firmware: complete (%d files)' % len(firmware_sources()))
        return
    log('firmware: %d file(s) missing, staging from the stock partitions'
        % len(missing))
    mounted = []
    try:
        if ensure_mount(APNHLOS, APNHLOS_DEV, 'vfat', 'ro'):
            mounted.append(APNHLOS)
        if ensure_mount(VENDOR, VENDOR_DEV, 'ext4', 'ro,noload'):
            mounted.append(VENDOR)
        for source, rel in firmware_sources():
            destination = FIRMWARE / rel
            if destination.exists():
                continue
            if source.is_symlink() or not source.is_file():
                # Vendor /firmware/wcnss.* are Android absolute symlinks.
                raise SetupError('firmware source is not a real file: %s' % source)
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, destination)
            destination.chmod(0o644)
    finally:
        for target in reversed(mounted):
            subprocess.run(['umount', str(target)], capture_output=True, text=True)
    still = firmware_missing()
    if still:
        raise SetupError('firmware still missing: %s' % ', '.join(still))
    log('firmware: staged %d file(s)' % len(missing))


def radio_up():
    if WLAN.exists():
        log('radio: wlan0 already present')
        return
    if not WCNSS_DEV.exists():
        raise SetupError('%s is missing; the WCNSS core did not probe'
                         % WCNSS_DEV)
    if not FWPATH.is_file():
        raise SetupError('%s is missing; the built-in wlan driver is not there'
                         % FWPATH)
    # Open and close only: a write to this device starts the calibration-data
    # protocol, which must not be triggered accidentally.
    log('radio: opening the WCNSS core once')
    os.close(os.open(WCNSS_DEV, os.O_RDWR | os.O_CLOEXEC))
    time.sleep(5)
    log('radio: starting the built-in wlan driver (fwpath=sta)')
    FWPATH.write_text('sta\n')
    deadline = time.monotonic() + 15
    while not WLAN.exists():
        if time.monotonic() >= deadline:
            raise SetupError('wlan0 did not appear; check dmesg for WCNSS errors')
        time.sleep(0.5)
    if P2P.exists():
        quiet('ip', 'link', 'set', 'dev', 'p2p0', 'down', timeout=30)
    log('radio: wlan0 is up; NetworkManager handles authentication')


def wifi_connected():
    if not WLAN.exists() or not shutil.which('nmcli'):
        return False
    state = quiet('nmcli', '-g', 'GENERAL.STATE', 'device', 'show', 'wlan0',
                  timeout=30).strip()
    return bool(re.match(r'^100\b', state))


def write_file(path, text, mode):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    path.chmod(mode)


def write_owned(path, text, mode, marker):
    """Never clobber a file this helper does not own."""
    if path.exists() or path.is_symlink():
        if path.is_symlink():
            raise SetupError('Refusing to replace a symlink: %s' % path)
        existing = path.read_text(errors='replace')[:512]
        if marker not in existing:
            raise SetupError('Existing file is not owned by this helper: %s'
                             % path)
    write_file(path, text, mode)


def self_install():
    source = Path(__file__).read_bytes()
    HELPER.parent.mkdir(parents=True, exist_ok=True)
    HELPER.write_bytes(source)
    HELPER.chmod(0o755)
    write_owned(INIT, INIT_TEXT, 0o755, 'J4_FIRSTBOOT_V1')
    write_owned(CONF, CONF_TEXT, 0o644, 'J4_FIRSTBOOT_V1')
    if not RUNLEVEL_LINK.is_symlink() and not RUNLEVEL_LINK.exists():
        RUNLEVEL_LINK.parent.mkdir(parents=True, exist_ok=True)
        quiet('rc-update', 'add', 'j4-firstboot', 'boot', timeout=60)
    log('service: j4-firstboot installed in the boot runlevel')


def install_wifi_service():
    write_owned(WIFI_SETUP, WIFI_TEXT, 0o755, 'J4_WIFI_HELPER_V1')
    if Path('/usr/local/sbin/j4-wifi').is_file():
        log('j4-wifi: already installed')
        return
    if not wifi_connected():
        log('j4-wifi: deferred; connect first with: nmcli dev wifi connect '
            '"SSID" password "PASSWORD"')
        return
    try:
        run(sys.executable, str(WIFI_SETUP), '--install', timeout=300)
        log('j4-wifi: service installed (persists across reboots)')
    except SetupError as exc:
        log('j4-wifi: %s' % exc)


def desktop_installed():
    return Path('/usr/bin/startlxqt').exists() or shutil.which('startlxqt') is not None


def install_desktop(detached):
    if desktop_installed():
        log('desktop: LXQt already installed')
        return
    if not shutil.which('apk'):
        log('desktop: apk is missing')
        return
    if not wifi_connected():
        log('desktop: deferred; no network yet')
        return
    write_owned(LXQT_SETUP, LXQT_TEXT, 0o755, 'J4_LXQT_SETUP_V1')
    if detached:
        # Never block boot on a package download that can take minutes.
        LOG.parent.mkdir(parents=True, exist_ok=True)
        handle = LOG.open('a')
        subprocess.Popen([sys.executable, str(LXQT_SETUP), '--install'],
                         stdout=handle, stderr=handle, stdin=subprocess.DEVNULL,
                         start_new_session=True)
        log('desktop: LXQt install started in the background')
        return
    log('desktop: installing LXQt (a few minutes)')
    try:
        run(sys.executable, str(LXQT_SETUP), '--install', timeout=2400)
        log('desktop: LXQt installed')
    except SetupError as exc:
        log('desktop: %s' % exc)


def status_lines():
    missing = firmware_missing()
    lines = [
        'firmware: %s' % ('complete' if not missing
                          else 'MISSING %d file(s)' % len(missing)),
        'wlan0: %s' % ('present' if WLAN.exists() else 'absent'),
        'network: %s' % ('connected' if wifi_connected() else 'not connected'),
        'j4-wifi service: %s' % ('installed' if Path('/usr/local/sbin/j4-wifi').is_file()
                                 else 'MISSING'),
        'LXQt desktop: %s' % ('installed' if desktop_installed() else 'MISSING'),
        'j4-recover: %s' % ('installed' if HELPER.is_file() else 'not installed'),
        'j4-firstboot service: %s' % ('enabled' if RUNLEVEL_LINK.is_symlink()
                                      else 'not enabled'),
    ]
    return lines


def check():
    check_device()
    for line in status_lines():
        print(line)


def recover(detached_desktop):
    check_device()
    self_install()
    stage_firmware()
    radio_up()
    install_wifi_service()
    install_desktop(detached_desktop)
    for line in status_lines():
        log(line)


def main():
    parser = argparse.ArgumentParser(description='J4+ recovery helper')
    parser.add_argument('--check', action='store_true',
                        help='report what is missing on this system')
    parser.add_argument('--install', action='store_true',
                        help='restore firmware, radio, j4-wifi and LXQt')
    parser.add_argument('--boot', action='store_true',
                        help='non-interactive recovery for the OpenRC service')
    args = parser.parse_args()
    if sum(bool(x) for x in (args.check, args.install, args.boot)) != 1:
        parser.error('pick exactly one of --check / --install / --boot')
    try:
        if args.check:
            check()
        else:
            recover(detached_desktop=args.boot)
    except SetupError as exc:
        log('ERROR: %s' % exc)
        sys.exit(1)


if __name__ == '__main__':
    main()
